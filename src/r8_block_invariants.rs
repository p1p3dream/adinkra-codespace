    #[test]
    fn hadamard_is_orthogonal() {
        let u = r8_fourier_basis();
        let ut = mat_transpose(&u);
        let product = mat_mul(&u, &ut);
        let id = mat_identity();
        for i in 0..8 {
            for j in 0..8 {
                assert!(
                    (product[i][j] - id[i][j]).abs() < 1e-12,
                    "U*U^T[{},{}] = {} (expected {})",
                    i,
                    j,
                    product[i][j],
                    id[i][j]
                );
            }
        }
    }

    #[test]
    fn hadamard_diagonalizes_r8_elements() {
        let u = r8_fourier_basis();
        let ut = mat_transpose(&u);
        for (idx, elem) in R8_ELEMENTS.iter().enumerate() {
            let mut rho = [[0.0; 8]; 8];
            for i in 0..8 {
                rho[i][elem[i]] = 1.0;
            }
            let diag = mat_mul(&u, &mat_mul(&rho, &ut));
            for i in 0..8 {
                for j in 0..8 {
                    if i != j {
                        assert!(
                            diag[i][j].abs() < 1e-12,
                            "R8 element {} not diagonalized: off-diag[{},{}] = {}",
                            idx,
                            i,
                            j,
                            diag[i][j]
                        );
                    }
                }
            }
        }
    }

