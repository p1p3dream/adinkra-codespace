//! R8-isotypic block projection of signed S8 representations.
//!
//! R8 = {e, r1, ..., r7} ≅ (Z/2)^3 acts regularly on {0,...,7} via the
//! Rana subgroup (arXiv:2304.09830 Eq. 3.23). The isotypic decomposition of
//! C^8 under this action is the Walsh-Hadamard (Fourier) transform.
//!
//! This module projects each L_I signed permutation into the R8 Fourier basis
//! using exact rational arithmetic (all entries are multiples of 1/8), then
//! classifies the 16 ordinary-closing S8 representations by their exact
//! diagonal tensors.
//!
//! SCOPE: These invariants classify recursion-basis construction families.
//! They are NOT proven physical invariants; the diagonal tensor depends on
//! the choice of R8 basis applied identically to bosons and fermions, and
//! transforms nontrivially under independent node basis changes and color
//! permutations. The mutation tests in this module document which
//! transformations preserve and which break the classification.

use crate::lr_matrix::AdinkraRep;
use crate::signed_perm::SignedPerm;
use serde::Serialize;

/// The 8 elements of R8 as 0-indexed permutations of {0,...,7}.
/// Generated by a=(01)(23)(45)(67), b=(02)(13)(46)(57), c=(04)(15)(26)(37).
/// Element ordering: e, a, b, ab, c, ac, bc, abc.
pub const R8_ELEMENTS: [[usize; 8]; 8] = [
    [0, 1, 2, 3, 4, 5, 6, 7], // e
    [1, 0, 3, 2, 5, 4, 7, 6], // a
    [2, 3, 0, 1, 6, 7, 4, 5], // b
    [3, 2, 1, 0, 7, 6, 5, 4], // ab
    [4, 5, 6, 7, 0, 1, 2, 3], // c
    [5, 4, 7, 6, 1, 0, 3, 2], // ac
    [6, 7, 4, 5, 2, 3, 0, 1], // bc
    [7, 6, 5, 4, 3, 2, 1, 0], // abc
];

/// Hadamard sign: (-1)^popcount(i & j).
fn hadamard_sign(i: usize, j: usize) -> i16 {
    if (i & j).count_ones() % 2 == 0 { 1 } else { -1 }
}

/// Walsh-Hadamard entry: U[i][j] = (1/sqrt(8)) * (-1)^popcount(i & j).
fn hadamard_entry(i: usize, j: usize) -> f64 {
    hadamard_sign(i, j) as f64 / (8.0_f64).sqrt()
}

/// The 8x8 Walsh-Hadamard matrix U (floating point, for legacy/validation).
pub fn r8_fourier_basis() -> [[f64; 8]; 8] {
    let mut u = [[0.0; 8]; 8];
    for i in 0..8 {
        for j in 0..8 {
            u[i][j] = hadamard_entry(i, j);
        }
    }
    u
}

/// Exact projection: compute 8 * (H L H^T)[a][b] as an i16.
///
/// For signed permutation L with perm pi and signs s_i:
///   8 * (H L H^T)[a][b] = sum_i  s_i * (-1)^(popcount(a&i) + popcount(pi(i)&b))
///
/// Each term is +/-1, so the sum is in [-8, 8].
pub fn project_exact(sp: &SignedPerm) -> [[i16; 8]; 8] {
    let mut result = [[0i16; 8]; 8];
    for a in 0..8 {
        for b in 0..8 {
            let mut sum = 0i16;
            for i in 0..8 {
                let s = sp.sign[i] as i16;
                let pi_i = sp.perm[i] as usize;
                let h_sign = hadamard_sign(a, i) * hadamard_sign(pi_i, b);
                sum += s * h_sign;
            }
            result[a][b] = sum;
        }
    }
    result
}

/// Per-color exact block projection.
#[derive(Debug, Clone, Serialize)]
pub struct ExactColorProjection {
    pub color: usize,
    /// 8 * (H L_I H^T), exact integers in [-8, 8].
    pub exact_matrix: [[i16; 8]; 8],
    /// Diagonal of exact_matrix.
    pub exact_diagonal: [i16; 8],
}

/// Full exact block report for one representation.
#[derive(Debug, Clone, Serialize)]
pub struct ExactBlockReport {
    pub label: String,
    pub projections: Vec<ExactColorProjection>,
    /// All 8 exact diagonals concatenated (n_colors * 8 entries).
    pub diagonal_tensor: Vec<i16>,
    /// Per-color sorted diagonal (for R8-automorphism-invariant comparison).
    pub sorted_diagonal_tensor: Vec<Vec<i16>>,
    /// Coupling fingerprint: for each irrep, bitmask of which others couple.
    pub coupling_fingerprint: [u8; 8],
}

/// R8 subgroup-restriction profile: per-color diagonal values organized
/// under the subgroup chain (Z/2)^3 > (Z/2)^2 > Z/2 > {e}.
#[derive(Debug, Clone, Serialize)]
pub struct R8SubgroupRestriction {
    pub label: String,
    /// Per-color, the 4 paired sums d[k] + d[k XOR 4] for (Z/2)^2 = <a,b>.
    pub z2_squared_sums: Vec<[i16; 4]>,
    /// Per-color, the 2 quadrupled sums for Z/2 = <a>.
    pub z2_sums: Vec<[i16; 2]>,
    /// Source pair type extracted from the label (e.g., "{CM,TM}").
    pub source_pair_type: String,
}

/// Compute the exact block report for one rep.
pub fn compute_exact_report(rep: &AdinkraRep, label: &str) -> ExactBlockReport {
    let n = rep.n;
    let mut projections = Vec::with_capacity(n);
    let mut diagonal_tensor = Vec::with_capacity(n * 8);
    let mut sorted_diagonal_tensor = Vec::with_capacity(n);
    let mut fingerprint = [0u8; 8];

    for color in 0..n {
        let exact = project_exact(&rep.l_matrices[color]);
        let diag: [i16; 8] = std::array::from_fn(|i| exact[i][i]);
        diagonal_tensor.extend_from_slice(&diag);

        let mut sorted = diag.to_vec();
        sorted.sort();
        sorted_diagonal_tensor.push(sorted);

        for i in 0..8 {
            for j in (i + 1)..8 {
                if exact[i][j] != 0 || exact[j][i] != 0 {
                    fingerprint[i] |= 1 << j;
                    fingerprint[j] |= 1 << i;
                }
            }
        }

        projections.push(ExactColorProjection {
            color,
            exact_matrix: exact,
            exact_diagonal: diag,
        });
    }

    ExactBlockReport {
        label: label.to_string(),
        projections,
        diagonal_tensor,
        sorted_diagonal_tensor,
        coupling_fingerprint: fingerprint,
    }
}

/// Compute R8 subgroup-restriction profile.
pub fn subgroup_restriction(report: &ExactBlockReport) -> R8SubgroupRestriction {
    let mut z2sq = Vec::with_capacity(report.projections.len());
    let mut z2s = Vec::with_capacity(report.projections.len());

    for proj in &report.projections {
        let d = &proj.exact_diagonal;
        z2sq.push(std::array::from_fn(|k| d[k] + d[k ^ 4]));
        z2s.push([d[0] + d[2] + d[4] + d[6], d[1] + d[3] + d[5] + d[7]]);
    }

    R8SubgroupRestriction {
        label: report.label.clone(),
        z2_squared_sums: z2sq,
        z2_sums: z2s,
        source_pair_type: extract_source_pair_type(&report.label),
    }
}

fn extract_source_pair_type(label: &str) -> String {
    let parts: Vec<&str> = label.split("->").collect();
    if parts.len() != 2 {
        return "unknown".to_string();
    }
    let first = parts[0].trim();
    let second = parts[1].split('_').next().unwrap_or("").trim();
    let mut pair = [first, second];
    pair.sort();
    format!("{{{},{}}}", pair[0], pair[1])
}

/// Classification summary across multiple reps.
#[derive(Debug, Clone, Serialize)]
pub struct ClassificationSummary {
    pub rep_count: usize,
    /// Classes by exact ordered diagonal tensor.
    pub ordered_classes: Vec<(Vec<i16>, Vec<String>)>,
    /// Classes by sorted diagonal multisets (R8-automorphism-invariant).
    pub sorted_classes: Vec<(Vec<Vec<i16>>, Vec<String>)>,
    /// Classes by coupling fingerprint.
    pub fingerprint_classes: Vec<([u8; 8], Vec<String>)>,
}

/// Classify reports by exact diagonal tensors.
pub fn classify(reports: &[ExactBlockReport]) -> ClassificationSummary {
    use std::collections::BTreeMap;

    let mut ordered: BTreeMap<Vec<i16>, Vec<String>> = BTreeMap::new();
    let mut sorted: BTreeMap<Vec<Vec<i16>>, Vec<String>> = BTreeMap::new();
    let mut fps: BTreeMap<[u8; 8], Vec<String>> = BTreeMap::new();

    for report in reports {
        ordered
            .entry(report.diagonal_tensor.clone())
            .or_default()
            .push(report.label.clone());
        sorted
            .entry(report.sorted_diagonal_tensor.clone())
            .or_default()
            .push(report.label.clone());
        fps.entry(report.coupling_fingerprint)
            .or_default()
            .push(report.label.clone());
    }

    ClassificationSummary {
        rep_count: reports.len(),
        ordered_classes: ordered.into_iter().collect(),
        sorted_classes: sorted.into_iter().collect(),
        fingerprint_classes: fps.into_iter().collect(),
    }
}

// --- Legacy floating-point API (kept for S4/V4 validation test) ---

fn mat_mul(a: &[[f64; 8]; 8], b: &[[f64; 8]; 8]) -> [[f64; 8]; 8] {
    let mut c = [[0.0; 8]; 8];
    for i in 0..8 {
        for k in 0..8 {
            if a[i][k] == 0.0 {
                continue;
            }
            for j in 0..8 {
                c[i][j] += a[i][k] * b[k][j];
            }
        }
    }
    c
}

fn mat_transpose(a: &[[f64; 8]; 8]) -> [[f64; 8]; 8] {
    let mut t = [[0.0; 8]; 8];
    for i in 0..8 {
        for j in 0..8 {
            t[i][j] = a[j][i];
        }
    }
    t
}

fn mat_identity() -> [[f64; 8]; 8] {
    let mut m = [[0.0; 8]; 8];
    for i in 0..8 {
        m[i][i] = 1.0;
    }
    m
}

