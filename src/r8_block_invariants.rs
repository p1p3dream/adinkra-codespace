    #[test]
    fn s4_v4_block_analysis_validates() {
        let cs = crate::lr_matrix::AdinkraRep {
            n: 4,
            d: 4,
            l_matrices: vec![
                SignedPerm::from_parts(vec![0, 1, 2, 3], vec![1, 1, 1, 1]).unwrap(),
                SignedPerm::from_parts(vec![1, 0, 3, 2], vec![1, -1, 1, -1]).unwrap(),
                SignedPerm::from_parts(vec![2, 3, 0, 1], vec![1, -1, -1, 1]).unwrap(),
                SignedPerm::from_parts(vec![3, 2, 1, 0], vec![1, 1, -1, -1]).unwrap(),
            ],
        };
        assert!(cs.verify_garden_algebra());

        let sqrt4 = 2.0_f64;
        let u4 = |i: usize, j: usize| -> f64 {
            let sign = if (i & j).count_ones() % 2 == 0 {
                1.0
            } else {
                -1.0
            };
            sign / sqrt4
        };
        let l1 = &cs.l_matrices[1];
        let mut m = [[0.0f64; 4]; 4];
        for row in 0..4 {
            m[row][l1.perm[row] as usize] = l1.sign[row] as f64;
        }
        let mut proj = [[0.0f64; 4]; 4];
        for i in 0..4 {
            for j in 0..4 {
                for k in 0..4 {
                    for l in 0..4 {
                        proj[i][j] += u4(i, k) * m[k][l] * u4(l, j);
                    }
                }
            }
        }
        let trace: f64 = (0..4).map(|i| proj[i][i]).sum();
        assert!(
            (trace - l1.trace() as f64).abs() < 1e-10,
            "trace must be preserved: {} vs {}",
            trace,
            l1.trace()
        );
    }

